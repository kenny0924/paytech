// 在运营入驻码页为 AE001 PayFac 签发一个入驻码（备注 ui-smoke），截图签发结果，明文码写入 scratchpad（测试数据）。
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = dirname(fileURLToPath(import.meta.url));
const { chromium } = createRequire(import.meta.url)(join(homedir(), '.npm/_npx/e41f203b7505f1fb/node_modules/playwright-core'));
const text = readFileSync('/Users/kenny/Desktop/Workspace/Code-MoR/test-environment/private/access.md', 'utf8');
const lang = process.argv[2] ?? 'en';
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(l => localStorage.setItem('i18n.locale', l), lang);
const page = await ctx.newPage();
page.on('console', m => { if (m.type() === 'error') console.log('console.error', m.text().slice(0, 200)); });
page.on('response', r => { if (r.url().includes('/api/') && r.status() >= 400) console.log('HTTP', r.status(), r.url(), r.headers()['x-request-id']); });
await page.goto('http://localhost:28080/'); await page.waitForTimeout(1500);
await page.getByLabel(/Email \/ initial account|Email \/ 初始化账号|邮箱|账号/).first().fill(text.match(/账号[:：]\s*(\S+)/)[1]);
await page.getByLabel(/^(Password|密码)$/).fill(text.match(/密码[:：]\s*(\S+)/)[1]);
await page.getByRole('button', { name: /^(Sign In|登\s*录)$/ }).click();
await page.getByText(/Sign Out|退出/).first().waitFor({ timeout: 20000 });
await page.goto('http://localhost:28080/client-onboarding/codes'); await page.waitForTimeout(2500);
await page.getByRole('button', { name: /Issue Code|签发入驻码|签发/ }).first().click(); await page.waitForTimeout(800);
const dlg = page.getByRole('dialog').last();
await dlg.locator('textarea').fill('ui-smoke browser check ' + new Date().toISOString());
await dlg.locator('input').nth(1).fill('3');
await page.screenshot({ path: join(HERE, `screens/ops-${lang}-codes_issue_filled.png`) });
await dlg.getByRole('button', { name: /^(Issue Code|签\s*发.*)$/ }).last().click(); await page.waitForTimeout(2500);
await page.screenshot({ path: join(HERE, `screens/ops-${lang}-codes_issue_result.png`), fullPage: true });
const shown = await page.getByRole('dialog').last().innerText().catch(() => '');
const code = (shown.match(/\b[A-Z0-9]{4}(?:-[A-Z0-9]{4}){1,4}\b/) ?? [])[0];
writeFileSync('/private/tmp/claude-501/-Users-kenny-Desktop-Workspace-Code-MoR/01ea5128-6d5a-487b-a761-584136eae2a1/scratchpad/ui-smoke-code.txt', code ?? '');
console.log('code captured:', !!code, '| dialog text:', shown.replace(/\b[A-Z0-9]{4}(?:-[A-Z0-9]{4}){1,4}\b/, '<code>').replace(/\s+/g, ' ').slice(0, 400));
await browser.close();
