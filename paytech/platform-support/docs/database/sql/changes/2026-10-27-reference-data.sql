-- ===== 0. 预检（只读）=====
DROP PROCEDURE IF EXISTS `ref_data_assert`;
DELIMITER //
CREATE PROCEDURE `ref_data_assert`(IN stage VARCHAR(16))
BEGIN
  IF stage = 'PRE' THEN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = DATABASE()
                AND table_name IN ('t_ref_currency', 't_ref_country', 't_ref_country_subdivision', 't_ref_industry', 't_ref_mcc')) THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'STOP: t_ref_* tables already exist; this change has been applied';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = DATABASE()
                    AND table_name = 't_currency_spec' AND column_name = 'version') THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'STOP: t_currency_spec.version missing; run changes/2026-10-20-currency-spec-version.sql first';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name = 't_country_region') THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'STOP: t_country_region missing; run changes/2026-10-22-country-region.sql and its seed first';
    END IF;
    IF (SELECT COUNT(*) FROM `t_country_region` WHERE `id` BETWEEN 2001 AND 2249) <> 249 THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'STOP: t_country_region does not hold the 249 seed rows (ids 2001-2249)';
    END IF;
    IF EXISTS (SELECT 1 FROM `t_currency_spec` WHERE `id` IN (1002, 1003, 1004)
                AND `currency` NOT IN ('AED', 'SAR', 'EGP')) THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'STOP: fixed currency ids 1002-1004 are used by other currencies';
    END IF;
  ELSEIF stage = 'BACKFILL' THEN
    IF EXISTS (SELECT 1 FROM `t_ref_currency` WHERE `numeric_code` IS NULL OR `name` IS NULL OR `symbol` IS NULL) THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'STOP: a t_ref_currency row is not an active ISO 4217 code; fix it before tightening NOT NULL';
    END IF;
    IF EXISTS (SELECT 1 FROM `t_ref_country` WHERE `alpha3_code` IS NULL OR `numeric_code` IS NULL OR `name` IS NULL) THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'STOP: a t_ref_country row was not backfilled';
    END IF;
    IF (SELECT COUNT(*) FROM `t_ref_currency` WHERE `currency_code` IN ('USD', 'AED', 'SAR', 'EGP') AND `status` = 'ACTIVE') <> 4 THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'STOP: USD / AED / SAR / EGP are not all ACTIVE';
    END IF;
    IF (SELECT COUNT(*) FROM `t_ref_country_subdivision`) <> 47 OR (SELECT COUNT(*) FROM `t_ref_industry`) <> 42
       OR EXISTS (SELECT 1 FROM `t_ref_industry` i LEFT JOIN `t_ref_mcc` m ON m.`mcc_code` = i.`default_mcc_code` AND m.`status` = 'ACTIVE'
                   WHERE i.`industry_level` = 2 AND m.`id` IS NULL) THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'STOP: subdivision / industry rows incomplete or a default MCC is not an ACTIVE t_ref_mcc row';
    END IF;
  ELSE
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'STOP: unknown assert stage';
  END IF;
END //
DELIMITER ;
CALL `ref_data_assert`('PRE');

