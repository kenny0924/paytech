package com.paytech.instance.manifest.compose;

import com.paytech.instance.manifest.InstanceManifest;
import com.paytech.instance.manifest.InstanceManifestValidator;
import com.paytech.instance.manifest.ManifestValidationResult;
import com.paytech.instance.manifest.ServiceRuntime;
import com.paytech.instance.manifest.catalog.ServiceCatalog;
import com.paytech.instance.manifest.catalog.ServiceDefinition;

import java.nio.file.Path;
import java.util.List;

/**
 * 每个 {@code services.<name>} 生成一个 Compose service：镜像占位 {@code paytech/<name>-service:<versions.platform>}、业务端口与
 * 管理端口（+1000）映射、{@code SPRING_APPLICATION_NAME}、{@code PAYTECH_SNOWFLAKE_WORKER_ID}、{@code PAYTECH_DB_NAME}（服务有数据库时）。
 *
 * @author Claude
 */
public class LocalEnvironmentComposeFragmentGeneratorImpl implements LocalEnvironmentComposeFragmentGenerator {

    private final ServiceCatalog serviceCatalog;

    private final InstanceManifestValidator validator;

    /**
     * 使用指定的服务清单与校验器。
     *
     * @param serviceCatalog 服务清单
     * @param validator 清单校验器
     */
    public LocalEnvironmentComposeFragmentGeneratorImpl(ServiceCatalog serviceCatalog,
        InstanceManifestValidator validator) {
        this.serviceCatalog = serviceCatalog;
        this.validator = validator;
    }

    @Override
    public ComposeFragmentResult generate(Path manifestFile) {
        ManifestValidationResult result = validator.validate(manifestFile);
        if (!result.isValid()) {
            return new ComposeFragmentResult(null, result.violations());
        }
        return new ComposeFragmentResult(render(result.manifest()), List.of());
    }

    private String render(InstanceManifest manifest) {
        StringBuilder yaml = new StringBuilder()
            .append("# Generated by paytech-instance-manifest from instance \"").append(manifest.instanceId())
            .append("\"; do not edit by hand.\n")
            .append("# Images are placeholders until each service publishes its own image.\n")
            .append("services:\n");
        for (ServiceRuntime service : manifest.services()) {
            ServiceDefinition definition = serviceCatalog.find(service.name()).orElseThrow();
            yaml.append("  ").append(service.name()).append(":\n")
                .append("    image: paytech/").append(service.name()).append("-service:")
                .append(manifest.platformVersion()).append('\n')
                .append("    ports:\n")
                .append("      - \"").append(service.port()).append(':').append(service.port()).append("\"\n")
                .append("      - \"").append(service.managementPort()).append(':').append(service.managementPort())
                .append("\"\n")
                .append("    environment:\n")
                .append("      SPRING_APPLICATION_NAME: ").append(definition.applicationName()).append('\n')
                .append("      PAYTECH_SNOWFLAKE_WORKER_ID: \"").append(service.snowflakeWorkerId()).append("\"\n");
            if (service.database() != null) {
                yaml.append("      PAYTECH_DB_NAME: ").append(service.database()).append('\n');
            }
        }
        return yaml.toString();
    }
}
